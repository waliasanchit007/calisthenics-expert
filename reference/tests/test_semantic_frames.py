# --- topology reconciliation ----------------------------------------------------------


def test_rejects_unknown_topology_without_assuming_33() -> None:
    manifest = minimal_manifest()
    manifest["pose_pipeline"]["landmark_topology"] = "future_pose_42_v1"
    issues = validate_frame_stream(manifest, [minimal_pose_frame()], "m.json", "f.ndjson")
    assert issues[0].code == "FRAME.TOPOLOGY_UNSUPPORTED"


def test_unsupported_topology_reports_the_manifest_field() -> None:
    manifest = minimal_manifest()
    manifest["pose_pipeline"]["landmark_topology"] = "future_pose_42_v1"
    issue = validate_frame_stream(manifest, [minimal_pose_frame()], "m.json", "f.ndjson")[0]
    assert issue.artifact_path == "m.json"
    assert issue.pointer == "/pose_pipeline/landmark_topology"


def test_unsupported_topology_does_not_report_landmark_cardinality() -> None:
    manifest = minimal_manifest()
    manifest["pose_pipeline"]["landmark_topology"] = "future_pose_42_v1"
    frame = minimal_pose_frame()
    template = frame["normalized_image_landmarks"][0]
    frame["normalized_image_landmarks"] += [
        dict(template, index=index) for index in range(LANDMARK_COUNT, 42)
    ]
    frame["world_landmarks"] = None
    assert codes(validate_frame_stream(manifest, [frame], "m.json", "f.ndjson")) == [
        "FRAME.TOPOLOGY_UNSUPPORTED"
    ]


