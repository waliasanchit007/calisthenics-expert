def test_repeated_validation_returns_identical_results() -> None:
    manifest = minimal_manifest()
    frames = [
        minimal_pose_frame(index=0, capture_ns=100),
        minimal_pose_frame(index=0, capture_ns=99),
    ]
    first = validate_frame_stream(manifest, frames, "m.json", "f.ndjson")
    second = validate_frame_stream(manifest, frames, "m.json", "f.ndjson")
    assert first == second
