from tests.samples import LANDMARK_COUNT, SESSION_ID, minimal_manifest, minimal_pose_frame

OTHER_SESSION_ID = "8e7d6c5b-4a39-4b28-9c17-0d6e5f4a3b21"

SYNTHETIC_TOPOLOGY = LandmarkTopology(
    name="synthetic_pose_4_v1",
    landmark_names=("alpha", "beta", "gamma", "delta"),
)
"""A second, deliberately non-33 topology, used to prove cardinality is not a fixed constant."""


def register(monkeypatch: pytest.MonkeyPatch, topology: LandmarkTopology) -> None:
    """Register one extra topology for the duration of a test.

    The registry is deliberately immutable in production — a released topology's names and
    order are already baked into exported landmark indexes — so a second topology has to be
    injected at its private seam to exercise a non-33 vocabulary.
    """
    monkeypatch.setitem(topology_module._TOPOLOGIES, topology.name, topology)

