def codes(issues: list[ValidationIssue]) -> list[str]:
    """Return only the issue codes, so a test asserts on behavior rather than on wording."""
    return [issue.code for issue in issues]


# --- topology registry ----------------------------------------------------------------


def test_topology_names_the_33_mediapipe_landmarks_in_order() -> None:
    assert get_topology("mediapipe_pose_33_v1").landmark_names == MEDIAPIPE_POSE_33_NAMES


def test_topology_landmark_count_comes_from_the_declared_names() -> None:
    assert get_topology("mediapipe_pose_33_v1").landmark_count == 33
    assert SYNTHETIC_TOPOLOGY.landmark_count == 4


def test_get_topology_rejects_an_unregistered_name() -> None:
    with pytest.raises(UnknownTopologyError):
        get_topology("future_pose_42_v1")


def test_cardinality_follows_the_declared_topology_rather_than_a_fixed_33(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    register(monkeypatch, SYNTHETIC_TOPOLOGY)
    manifest = minimal_manifest()
    manifest["pose_pipeline"]["landmark_topology"] = SYNTHETIC_TOPOLOGY.name
    frame = minimal_pose_frame()
    frame["world_landmarks"] = None
    issues = validate_frame_stream(manifest, [frame], "m.json", "f.ndjson")
    assert codes(issues) == ["FRAME.LANDMARK_COUNT"]
    assert issues[0].expected == 4
    assert issues[0].actual == 33


def test_accepts_a_stream_matching_a_non_33_topology(monkeypatch: pytest.MonkeyPatch) -> None:
    register(monkeypatch, SYNTHETIC_TOPOLOGY)
    manifest = minimal_manifest()
    manifest["pose_pipeline"]["landmark_topology"] = SYNTHETIC_TOPOLOGY.name
    frame = minimal_pose_frame()
    frame["normalized_image_landmarks"] = frame["normalized_image_landmarks"][:4]
    frame["world_landmarks"] = frame["world_landmarks"][:4]
    assert validate_frame_stream(manifest, [frame], "m.json", "f.ndjson") == []


