"""Semantic invariants of a raw pose stream read against its session manifest.

Every expected value in this module is written literally. Nothing here is generated by the
production topology registry or validator, so a wrong implementation cannot make its own
output the expectation.
"""

import copy

import pytest

from observation_contracts import topology as topology_module
